// Generates src/snippets/blog-posts.ts from blog post frontmatter.
// Replaces the `virtual:blog` module removed in vocs 2.x.
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const BLOG_DIR = 'src/pages/blog'
const OUT_FILE = 'src/snippets/blog-posts.ts'

function parseFrontmatter(contents) {
  const match = contents.match(/^---\r?\n([\s\S]*?)\r?\n---/)
  if (!match) return {}
  const frontmatter = {}
  let currentKey = null
  for (const line of match[1].split(/\r?\n/)) {
    const listItem = line.match(/^\s+-\s+"?([^"]+)"?\s*$/)
    if (listItem && currentKey) {
      if (!Array.isArray(frontmatter[currentKey])) frontmatter[currentKey] = []
      frontmatter[currentKey].push(listItem[1])
      continue
    }
    const pair = line.match(/^(\w[\w-]*):\s*(.*)$/)
    if (pair) {
      currentKey = pair[1]
      const value = pair[2].trim().replace(/^"(.*)"$/, '$1')
      if (value) frontmatter[currentKey] = value
    }
  }
  return frontmatter
}

try {
  const files = (await readdir(BLOG_DIR)).filter((f) => f.endsWith('.mdx'))
  const posts = []
  for (const file of files) {
    const contents = await readFile(join(BLOG_DIR, file), 'utf-8')
    const frontmatter = parseFrontmatter(contents)
    if (!frontmatter.title || !frontmatter.date) {
      console.error(`Skipping ${file}: missing title or date frontmatter`)
      continue
    }
    posts.push({
      authors: frontmatter.authors,
      date: frontmatter.date,
      description: frontmatter.description,
      path: `/blog/${file.replace(/\.mdx$/, '')}`,
      title: frontmatter.title,
    })
  }
  posts.sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime())
  const header = `// Generated by scripts/generate-blog-list.mjs — do not edit.\n\nexport type BlogPost = {\n  authors?: string[]\n  date: string\n  description?: string\n  path: string\n  title: string\n}\n\nexport const posts: BlogPost[] = `
  await writeFile(OUT_FILE, `${header}${JSON.stringify(posts, null, 2)}\n`)
  console.log(`Generated ${OUT_FILE} with ${posts.length} posts`)
} catch (error) {
  console.error('Failed to generate blog posts list:', error)
  process.exitCode = 1
}
